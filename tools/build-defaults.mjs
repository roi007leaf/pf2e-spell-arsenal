import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inferSpellRule } from '../scripts/spell-parser.js';
import { matchSpellVisual } from '../scripts/spell-matching.js';

const [sourceRoot, configFile] = process.argv.slice(2);
if (!sourceRoot || !configFile) throw new Error('Usage: node tools/build-defaults.mjs <PF2e packs/spells directory> <Tile Arsenal configs.json>');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const configs = JSON.parse(readFileSync(configFile, 'utf8')).configurations;
const spells = readdirSync(sourceRoot, { recursive: true }).filter(file => file.endsWith('.json'))
  .map(file => ({ file, item: JSON.parse(readFileSync(path.join(sourceRoot, file), 'utf8')) })).filter(row => row.item.type === 'spell');
const audit = [], defaults = [], seen = new Set();
for (const { file, item } of spells.sort((a, b) => a.item.name.localeCompare(b.item.name) || a.file.localeCompare(b.file))) {
  const match = matchSpellVisual(item);
  const slug = path.basename(file, '.json');
  const { rule } = inferSpellRule(item, configs, slug);
  const preset = Object.values(configs).find(p => p.name === match.effect);
  let reason = match.reason;
  let enabled = match.confidence !== 'review' && Boolean(preset);
  if (file.split(path.sep).includes('rituals')) { enabled = false; reason = 'Ritual: no standard spell-cast workflow'; }
  const supported = ['Tile', 'AmbientLight', 'AmbientSound', 'Region'];
  if (preset && Object.values(preset.configs).some(part => !supported.includes(part.type) || (rule.kind !== 'area' && part.type === 'Region'))) {
    enabled = false; reason = 'Preset document types unsupported for this trigger';
  }
  if (rule.kind === 'caster') { enabled = false; reason = 'Target/object placement needs manual review; caster placement would be misleading'; }
  const durationText = item.system.duration?.value?.trim() ?? '';
  if (durationText && !/^(?:up to\s+)?\d+(?:\.\d+)?\s*(seconds?|rounds?|minutes?|hours?|days?)$/i.test(durationText)) {
    enabled = false; reason = 'Variable, sustained or open-ended duration requires review';
  }
  if (item.system.duration?.sustained) { enabled = false; reason = 'Sustained expiration requires GM review'; }
  const area = item.system.area;
  if (area) {
    const cells = area.value / 5;
    const estimate = ['burst', 'emanation', 'cylinder'].includes(area.type) ? Math.PI * cells * cells : area.type === 'cone' ? Math.PI * cells * cells / 4 : ['square', 'cube'].includes(area.type) ? cells * cells : cells;
    if (estimate > 120) { enabled = false; reason = 'Base area likely exceeds the 120-cell visual limit'; }
  }
  if (seen.has(item.name.toLowerCase())) { enabled = false; reason = 'Duplicate display name: runtime matches by spell name'; }
  if (enabled) {
    rule.effect = match.effect;
    rule.enabled = true;
    rule.sourceUuid = `Compendium.pf2e.spells-srd.Item.${item._id}`;
    rule.stageMode = 'auto';
    rule.stage = Math.min(...Object.values(preset.configs).map(part => part.stage));
    if (rule.kind === 'damage') { rule.instant = true; rule.duration = 0; rule.highlight = false; }
    defaults.push(rule); seen.add(item.name.toLowerCase());
  }
  audit.push({ spell: item.name, uuid: `Compendium.pf2e.spells-srd.Item.${item._id}`, source: file.replaceAll('\\', '/'), effect: match.effect,
    trigger: rule.kind, status: enabled ? 'enabled' : match.effect ? 'review' : 'unmatched', reason });
}
const starters = ['Caustic Blast', 'Scatter Scree', 'Fireball', 'Grease', 'Grim Tendrils'];
defaults.sort((a,b) => (starters.includes(a.spell) ? starters.indexOf(a.spell) : 99) - (starters.includes(b.spell) ? starters.indexOf(b.spell) : 99) || a.spell.localeCompare(b.spell));
mkdirSync(path.join(root, 'docs'), { recursive: true });
writeFileSync(path.join(root, 'scripts/default-rules.js'), `// Generated by tools/build-defaults.mjs from PF2e 8.5.1 and Tile Arsenal 1.1.1.\nexport const DEFAULT_RULES = ${JSON.stringify(defaults, null, 2)};\n`);
const quote = value => `"${String(value).replaceAll('"', '""')}"`;
writeFileSync(path.join(root, 'docs/spell-visual-audit.csv'), ['spell,uuid,source,effect,trigger,status,reason', ...audit.map(row => Object.values(row).map(quote).join(','))].join('\n') + '\n');
const presets = Object.values(configs).map(p => ({ name: p.name, preview: p.img, textures: [...new Set(Object.values(p.configs).flatMap(part => [part.config?.['texture.src']].flat(Infinity)).filter(Boolean))], stages: [...new Set(Object.values(p.configs).map(part => part.stage))], types: [...new Set(Object.values(p.configs).map(part => part.type))], enabledSpells: defaults.filter(rule => rule.effect === p.name).length }));
writeFileSync(path.join(root, 'docs/preset-audit.json'), JSON.stringify({ pf2e: '8.5.1', tileArsenal: '1.1.1', spells: audit.length, enabled: defaults.length, presets }, null, 2) + '\n');
console.log(JSON.stringify({ spells: audit.length, enabled: defaults.length, review: audit.filter(row => row.status === 'review').length, unmatched: audit.filter(row => row.status === 'unmatched').length, effects: presets.filter(p => p.enabledSpells).map(p => `${p.name}: ${p.enabledSpells}`) }));
